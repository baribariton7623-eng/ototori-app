import type { ReactNode } from 'react';
import { OPERATOR_ENV, operator, type OperatorKey } from './operator';

/** 運営者情報の値。未設定なら赤字で環境変数名を出す */
function O({ k }: { k: OperatorKey }) {
  const value = operator[k];
  if (value) return <>{value}</>;
  return <span className="font-medium text-red-700 bg-red-50 px-1 rounded">【未設定: {OPERATOR_ENV[k]}】</span>;
}

function LegalLayout({ title, children }: { title: string; children: ReactNode }) {
  return (
    <article className="card space-y-4 text-sm leading-relaxed [&_h2]:font-semibold [&_h2]:text-base [&_h2]:mt-5 [&_ol]:list-decimal [&_ol]:pl-5 [&_ol]:space-y-1 [&_ul]:list-disc [&_ul]:pl-5 [&_ul]:space-y-1">
      <h1 className="text-xl font-semibold">{title}</h1>
      {children}
      <p className="text-xs text-stone-500 pt-4">
        施行日: <O k="effectiveDate" />
        <br />
        {operator.serviceName} 運営者: <O k="name" />
      </p>
    </article>
  );
}

